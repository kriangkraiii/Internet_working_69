"""cml_lab.py — Infrastructure-as-Code: สร้าง/ควบคุม topology บน Cisco Modeling Labs (DevNet Sandbox) ผ่าน CML API

  python scripts/cml_lab.py build              สร้าง lab จาก inventory.yaml + ใส่ Day-0 config + start + รอ boot
  python scripts/cml_lab.py status             สถานะ node และ link
  python scripts/cml_lab.py export             ดาวน์โหลด topology -> topology/Capstone-P3.yaml (ไฟล์ส่งงาน)
  python scripts/cml_lab.py capture start --a R1-HQ --b R0-ISP
  python scripts/cml_lab.py capture stop  --a R1-HQ --b R0-ISP --name 01_ike_esp   -> captures/01_ike_esp.pcap
  python scripts/cml_lab.py flap --a R2-BR1 --b R0-ISP --times 3     ตัด/ต่อ "สาย" จริงใน CML (สมจริงกว่า shutdown)
  python scripts/cml_lab.py ssh-key            (สำรอง) ถ้า SSH ยังเข้าไม่ได้หลัง boot: สร้าง RSA key ผ่าน console server
  python scripts/cml_lab.py stop | wipe | delete

ต้องติดตั้ง virl2-client ให้เวอร์ชันตรงกับ CML ของ sandbox เช่น CML 2.8.x -> pip install "virl2-client==2.8.*"
"""
from __future__ import annotations

import argparse
import time
import warnings
from pathlib import Path

from common import ROOT, banner, config_lines, connect, load_inventory, render

warnings.filterwarnings("ignore")  # sandbox ใช้ self-signed cert

# ตำแหน่งบน canvas ของ CML (x, y)
LAYOUT = {"R0-ISP": (0, -200), "R1-HQ": (-300, 0), "R2-BR1": (0, 50), "R3-DC": (300, 0)}


def client_and_cfg():
    from virl2_client import ClientLibrary

    inv = load_inventory()
    cml = next(iter(inv.values()))["cml"]
    client = ClientLibrary(f"https://{cml['host']}", cml["username"], cml["password"], ssl_verify=False)
    return client, cml, inv


def get_lab(client, title):
    labs = client.find_labs_by_title(title)
    if not labs:
        raise SystemExit(f"[!] ไม่พบ lab '{title}' — รัน build ก่อน")
    return labs[0]


def set_config(node, text: str) -> None:
    if hasattr(type(node), "configuration"):
        node.configuration = text
    else:  # virl2-client รุ่นเก่า
        node.config = text


def port(node, label: str | None = None):
    if label:
        return node.get_interface_by_label(label)
    return node.next_available_interface() or node.create_interface()


def build(client, cml, inv, with_pcs: bool) -> None:
    if client.find_labs_by_title(cml["lab"]):
        raise SystemExit(f"[!] มี lab '{cml['lab']}' อยู่แล้ว — ใช้ status หรือ delete ก่อน")
    lab = client.create_lab(cml["lab"])
    lab.description = "KKU Capstone P3 — Netmiko automation on Real IOS (generated by cml_lab.py)"

    nodes = {}
    for name, dev in inv.items():
        x, y = LAYOUT.get(name, (0, 0))
        n = lab.create_node(name, cml["node_definition"], x, y, populate_interfaces=True)
        day0 = "\n".join(config_lines(render(dev, "bootstrap.j2")))
        set_config(n, day0)
        nodes[name] = n
        print(f"[+] node {name:7} ({cml['node_definition']}) mgmt {dev['mgmt_ip']}")

    # OOB management: router Gi0/3 -> SW-MGMT -> External Connector (bridge0 = วง 10.10.20.0/24 ของ sandbox)
    sw = lab.create_node("SW-MGMT", "unmanaged_switch", 0, 300, populate_interfaces=True)
    ext = lab.create_node("EXT-MGMT", "external_connector", 0, 450, populate_interfaces=True)
    set_config(ext, "bridge0")
    lab.create_link(port(ext), port(sw))
    for name, dev in inv.items():
        lab.create_link(port(nodes[name], dev["mgmt_if"]), port(sw))

    # WAN: R0-ISP Gi0/x <-> site Gi0/0
    for itf in inv["R0-ISP"]["interfaces"]:
        peer = itf["desc"].replace("to ", "")
        lab.create_link(port(nodes["R0-ISP"], itf["name"]), port(nodes[peer], inv[peer]["wan"]["name"]))
        print(f"[+] link  R0-ISP {itf['name']} <-> {peer} {inv[peer]['wan']['name']}")

    # LAN: switch ต่อ site ทำให้ Gi0/1 up/up (+ PC ถ้าต้องการสร้างทราฟฟิกให้ NetFlow)
    for name, dev in inv.items():
        if dev["role"] == "isp":
            continue
        x, y = LAYOUT[name]
        lsw = lab.create_node(f"LAN-{name.split('-')[1]}", "unmanaged_switch", x, y + 150, populate_interfaces=True)
        lab.create_link(port(nodes[name], dev["lan"]["name"]), port(lsw))
        if with_pcs:
            pc = lab.create_node(f"PC-{name.split('-')[1]}", "desktop", x + 120, y + 200, populate_interfaces=True)
            lab.create_link(port(pc), port(lsw))

    banner(f"Starting lab '{cml['lab']}' — IOSv ใช้เวลา boot ประมาณ 3–6 นาที")
    lab.start(wait=True)
    print("[OK] lab converged — ตรวจด้วย: ping 10.10.20.181-184 แล้ว python scripts/lab_28_1_3.py")


def find_link(lab, a: str, b: str):
    for link in lab.links():
        if {link.node_a.label, link.node_b.label} == {a, b}:
            return link
    raise SystemExit(f"[!] ไม่พบลิงก์ {a} <-> {b}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["build", "status", "export", "capture", "flap", "ssh-key", "stop", "wipe", "delete"])
    ap.add_argument("sub", nargs="?", choices=["start", "stop"], help="ใช้กับ capture")
    ap.add_argument("--a")
    ap.add_argument("--b")
    ap.add_argument("--name", default="capture")
    ap.add_argument("--times", type=int, default=3)
    ap.add_argument("--with-pcs", action="store_true")
    args = ap.parse_args()

    client, cml, inv = client_and_cfg()
    if args.action == "build":
        return build(client, cml, inv, args.with_pcs)
    if args.action == "ssh-key":
        for name, dev in inv.items():
            conn = connect(dev, via="console", tag="sshkey")
            if "Key name" in conn.send_command("show crypto key mypubkey rsa"):
                print(f"[=] {name}: มี RSA key อยู่แล้ว")
            else:
                conn.send_config_set(["crypto key generate rsa general-keys modulus 2048"],
                                     read_timeout=120, cmd_verify=False)
                print(f"[+] {name}: สร้าง RSA key แล้ว")
            conn.save_config()
            conn.disconnect()
        return

    lab = get_lab(client, cml["lab"])
    if args.action == "status":
        lab.sync()
        for n in lab.nodes():
            print(f"{n.label:10} {n.node_definition:20} {n.state}")
        for link in lab.links():
            print(f"link {link.node_a.label}:{link.interface_a.label} <-> {link.node_b.label}:{link.interface_b.label}  {link.state}")
    elif args.action == "export":
        out = ROOT / "topology" / f"{cml['lab']}.yaml"
        out.parent.mkdir(exist_ok=True)
        out.write_text(lab.download(), encoding="utf-8")
        print(f"[OK] {out.relative_to(ROOT)}")
    elif args.action == "capture":
        # เรียก CML REST API ตรงๆ — ใช้ได้ทั้ง virl2-client รุ่นเก่าที่ไม่มี start_capture และรุ่นใหม่
        link = find_link(lab, args.a, args.b)
        api = lab._session
        base = f"labs/{lab.id}/links/{link.id}/capture"
        keyfile = ROOT / "captures" / f".key_{args.a}_{args.b}"
        keyfile.parent.mkdir(exist_ok=True)
        if args.sub == "start":
            r = api.put(f"{base}/start", json={"maxpackets": 100000, "maxtime": 600})
            r.raise_for_status()
            info = r.json() if r.content else {}
            key = (info.get("config") or {}).get("link_capture_key") or info.get("link_capture_key") or link.id
            keyfile.write_text(str(key))
            print(f"[+] capturing {args.a} <-> {args.b} (สูงสุด 10 นาที) key={key}")
        else:
            api.put(f"{base}/stop")
            time.sleep(2)
            key = keyfile.read_text().strip() if keyfile.exists() else link.id
            data = b""
            for k in dict.fromkeys([key, link.id]):
                try:
                    r = api.get(f"pcap/{k}")
                except Exception as exc:
                    print(f"   pcap/{k}: {str(exc).splitlines()[0]}")
                    continue
                if r.status_code == 200 and r.content[:4] in (b"\xd4\xc3\xb2\xa1", b"\xa1\xb2\xc3\xd4", b"\x0a\x0d\x0d\x0a"):
                    data = r.content
                    break
            if not data:
                raise SystemExit(f"[!] ดาวน์โหลด pcap ไม่สำเร็จ (HTTP {r.status_code}) — ใช้ CML UI: คลิกลิงก์ > Packet Capture > Download")
            out = ROOT / "captures" / f"{args.name}.pcap"
            out.write_bytes(data)
            print(f"[OK] {out.relative_to(ROOT)} ({len(data)} bytes) — เปิดด้วย Wireshark")
    elif args.action == "flap":
        link = find_link(lab, args.a, args.b)
        for i in range(args.times):
            link.stop(wait=True)
            print(f"[{time.strftime('%H:%M:%S')}] flap {i + 1}/{args.times}: link DOWN")
            time.sleep(8)
            link.start(wait=True)
            print(f"[{time.strftime('%H:%M:%S')}] flap {i + 1}/{args.times}: link UP")
            time.sleep(12)
    elif args.action == "stop":
        lab.stop()
    elif args.action == "wipe":
        lab.stop()
        lab.wipe()
    elif args.action == "delete":
        lab.stop()
        lab.wipe()
        lab.remove()
    print("done")


if __name__ == "__main__":
    main()
